export const getPlantSpriteFrame = (flowerId = 1) => {
  const id = Number.isFinite(flowerId) && flowerId > 0 ? Math.floor(flowerId) : 1;
  // Older entries used IDs up to 212; map them deterministically into this atlas.
  const index = (id - 1) % frameAnchors.length;
  const [anchorX, anchorY] = frameAnchors[index];
  return { column: index % 10, row: Math.floor(index / 10), anchorX, anchorY };
};
